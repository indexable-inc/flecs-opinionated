"""Moves vendor/flecs to the current Flecs and regenerates what depends on it.

    uv run scripts/bump_flecs.py --flecs ~/src/flecs                     # rebase the fork onto upstream, then pin it
    uv run scripts/bump_flecs.py --flecs ~/src/flecs --pin fork/master   # pin a fork commit as it is, no rebase
    uv run scripts/bump_flecs.py --bindings-only                         # only regenerate the bindings

The Flecs we want is indexable-inc/flecs `master`: upstream SanderMertens/flecs `master` plus the commits of our open
upstream PRs, rebased (each PR also has its own branch on the fork). Steps (vendor/flecs/SOURCE.md, "Bumping"):

1. fetches upstream `master` and the fork's `master` into the checkout (remotes `upstream` and `fork`, added if
   missing), checks out a local `master` at the fork's `master` and rebases it onto upstream `master`; commits whose
   PR merged upstream drop out as empty. A conflict stops here (regenerate `distr/` with bake for the conflicting
   commit, `git rebase --continue`, then rerun with `--pin master`). Nothing is pushed: the script prints the
   `git push --force-with-lease` for the fork;
2. copies `distr/flecs.c` and `distr/flecs.h` of the result (upstream and each PR commit carry their amalgamation;
   no bake) to vendor/flecs/distr;
3. regenerates crates/flecs_ecs_sys/src/bindings.rs (FLECS_DEBUG) and bindings_release.rs (FLECS_NDEBUG) with the
   bindgen CLI (0.72, `BINDGEN` or on PATH; e.g. `nix shell nixpkgs#rust-bindgen`), with the options of
   crates/flecs_ecs_sys/build.rs `generate_bindings` (its doc comment callback is redone here on the output);
4. rewrites the pin block of vendor/flecs/SOURCE.md: the fork commit, the upstream commit it is based on, and the
   fork's commits on top;
5. prints the C API diff of flecs.h: removed, changed and added declarations, which is what crates/flecs_ecs and
   crates/flecs-c/csrc/glue.c must be ported for.

Needs nothing outside the standard library.
"""

import argparse
import asyncio
import os
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DISTR = ROOT / "vendor" / "flecs" / "distr"
SOURCE_MD = ROOT / "vendor" / "flecs" / "SOURCE.md"
SYS = ROOT / "crates" / "flecs_ecs_sys"
# The commit Flecs 4.1.6 shipped as; SOURCE.md counts from it.
BASE_416 = "6e4cd338a"
UPSTREAM = ("upstream", "https://github.com/SanderMertens/flecs")
